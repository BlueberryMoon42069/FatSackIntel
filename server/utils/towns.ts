/** Get [lng, lat] for a town name (tries uppercase first, then as-is) */
export function getTownCoords(town: string): [number, number] | undefined {
  return townCentroids[town.toUpperCase()] ?? townCentroids[town];
}

/** Normalize town name to uppercase, trimmed */
export function normalizeTownName(town: string): string {
  return town.trim().toUpperCase();
}

/** Find nearest town within ~10 miles (0.15°) of given coordinates */
export function findNearestTown(lng: number, lat: number): string | null {
  let best: string | null = null;
  let bestDist = Infinity;
  for (const [town, [tLng, tLat]] of Object.entries(townCentroids)) {
    if (town !== town.toUpperCase()) continue; // skip any lowercase duplicates
    const d = Math.sqrt((lng - tLng) ** 2 + (lat - tLat) ** 2);
    if (d < bestDist) { bestDist = d; best = town; }
  }
  return bestDist < 0.15 ? best : null;
}

/** Return all uppercase town names that have centroid coordinates */
export function getAllTownNames(): string[] {
  return Object.keys(townCentroids).filter(t => t === t.toUpperCase());
}
